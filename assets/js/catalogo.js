/* Lista achatada, usada pelo seletor do formulário de contato. */
export function listaServicos(){
  const out = [];
  CATEGORIAS.forEach(cat => {
    cat.servicos.forEach(s => {
      out.push({
        valor: `${cat.id}::${s.nome}`,
        casa: CASAS[cat.casa].nome,
        categoria: cat.titulo,
        nome: s.nome,
        tipo: s.tipo,
      });
    });
  });
  return out;
}
